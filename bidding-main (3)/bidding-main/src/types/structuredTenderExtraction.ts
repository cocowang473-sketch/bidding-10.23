export type ExtractionCategoryKey =
  | 'project' // 一、项目基本信息（Project）
  | 'timeline' // 二、投标关键时间与提交流程（Bid Timeline & Submission）
  | 'compliance' // 三、文件组成与合规性要求（Compliance）
  | 'pricing' // 四、报价与计价规则（Pricing Rules）
  | 'boq' // 五、BOQ工程量清单与组价要素（BOQ & Costing Inputs）
  | 'contract' // 六、合同条款与风险点（Contract & Risks）
  | 'translation' // 七、翻译与双语一致性（Translation QC）
  | 'confidentiality'; // 八、保密与信息安全（Confidentiality）

export type ExtractionDocSource =
  | 'doc1' // Doc 1: 01_招标通告与投标准备须知 (Avis & RC)
  | 'doc2' // Doc 2: 02_专用行政与技术合同条款 (CCAP & CCTP)
  | 'doc3' // Doc 3: 03_工程量清单与计价规则 (BQE & Règles de Prix)
  | 'addendum'; // 补充文件/补遗纪要 (Addenda)

export type ExtractionStatus =
  | 'extracted' // 从文件中提取的内容（绿色高亮，含出处与原句定位）
  | 'suggested'; // 需要建议填写 / 待确认的内容（不标颜色/默认白底，需人工复核确认）

export type ExtractionPriority =
  | 'preset' // 按“预设关键点”优先提取
  | 'discovered'; // 补充识别其他可能重要的内容

export interface ExtractionFieldItem {
  id: string;
  categoryKey: ExtractionCategoryKey;
  fieldNameZh: string; // 字段名称 (中文)
  fieldNameFr: string; // 字段名称 (法文)
  docSource: ExtractionDocSource; // 来源核心卷册
  docSourceName: string; // 来源卷册名称
  sourceClause?: string; // 条款编号，如 "RC 须知第 1.1 款"
  pageNumber?: number; // 原文所在页码
  status: ExtractionStatus; // 'extracted' (绿色) | 'suggested' (不标颜色)
  priority: ExtractionPriority; // 'preset' (预设关键点) | 'discovered' (补充识别)
  value: string; // 当前值或提取值
  valueFr?: string; // 法语原文值
  suggestedValue?: string; // 建议填写值 (当待确认时)
  evidenceSnippetZh?: string; // 中文佐证摘录
  evidenceSnippetFr?: string; // 法语原句摘录
  confidenceScore?: number; // 提取置信度 (0-100)
  note?: string; // 造价工程师复核备注 / 待确认说明
  linkedVariableKey?: string; // 联动标书组件的变量 key
  confirmedBy?: string; // 人工确认人 (确认后转为已提取绿色)
  confirmedAt?: string;
}

